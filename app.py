# Reads DOCX generated by the ITLadder production guide, plus JSON schema v1.
def parse_docx(raw):
 doc=Document(io.BytesIO(raw)); lines=[p.text.strip() for p in doc.paragraphs if p.text.strip()]
 universal_master='';universal_negative='';reels=[]; reel=None;clip=None;section=''
 for i,t in enumerate(lines):
  if t.lower()=='universal character consistency master' and i+1<len(lines):universal_master=lines[i+1]
  if t.lower()=='universal negative prompt' and i+1<len(lines):universal_negative=lines[i+1]
  m=re.match(r'REEL\s+(\d+)\s*[—–:-]\s*(.+)',t,re.I)
  if m:
   reel={'id':int(m.group(1)),'title':m.group(2),'master':'','negative':'','clips':[]};reels.append(reel);clip=None;section='';continue
  if reel is None:continue
  if t.lower()=='master consistency prompt':section='master';clip=None;continue
  if t.lower()=='reel-specific negative prompt':section='negative';clip=None;continue
  c=re.match(r'Clip\s+(\d+)\s*\|',t,re.I)
  if c:
   clip={'index':int(c.group(1)),'voiceover':'','start_frame':'','end_frame':'','motion':''};reel['clips'].append(clip);section='clip';continue
  if section=='master' and not reel['master']:reel['master']=t
  elif section=='negative' and not reel['negative']:reel['negative']=t
  elif clip:
   for prefix,key in [('Voiceover (original, approx. 10 sec):','voiceover'),('IMAGE / START FRAME:','start_frame'),('IMAGE / END FRAME:','end_frame'),('IMAGE-TO-VIDEO / 10s:','motion'),('START FRAME:','start_frame'),('END FRAME:','end_frame'),('VIDEO PROMPT:','motion'),('VOICEOVER:','voiceover')]:
    if t.lower().startswith(prefix.lower()):clip[key]=t[len(prefix):].strip();break
 return {'schema':'itladder-reels-v1','aspect_ratio':'9:16','universal_master':universal_master,'universal_negative':universal_negative,'reels':reels}

def validate(data):
 reels=data.get('reels',[])
 if not isinstance(reels,list) or not 1<=len(reels)<=100:raise HTTPException(400,'Import 1–100 reels')
 for r in reels:
  if not isinstance(r.get('clips'),list) or not 1<=len(r['clips'])<=20:raise HTTPException(400,'Each reel needs 1–20 clips')
  for c in r['clips']:
   if not (c.get('motion') or c.get('start_frame')):raise HTTPException(400,'Each clip requires a motion or start-frame prompt')
 return data

@app.post('/api/import')
async def import_file(file:UploadFile=File(...)):
 raw=await file.read()
 if len(raw)>12_000_000:raise HTTPException(413,'Maximum upload 12 MB')
 try:
  if file.filename.lower().endswith('.docx'):data=parse_docx(raw)
  elif file.filename.lower().endswith('.json'):data=json.loads(raw)
  elif file.filename.lower().endswith('.zip'):
   with zipfile.ZipFile(io.BytesIO(raw)) as z:
    names=[n for n in z.namelist() if not n.startswith('__MACOSX/')]
    j=next((n for n in names if n.endswith('.json')),None)
    d=next((n for n in names if n.endswith('.docx')),None)
    if j:data=json.loads(z.read(j))
    elif d:data=parse_docx(z.read(d))
    else:raise ValueError('ZIP must contain a JSON or DOCX prompt file')
  else:raise ValueError('Use DOCX, JSON or ZIP')
  validate(data)
 except (ValueError,KeyError,zipfile.BadZipFile) as e:raise HTTPException(400,str(e))
 except Exception as e:raise HTTPException(400,'Could not parse file: '+str(e))
 ident=uuid.uuid4().hex;DATA[ident]=data
 return {'dataset_id':ident,'data':data}

class RunRequest(BaseModel):
 dataset_id:str
 reel_ids:list[int]|None=None
 mode:str='demo'
 api_key:str|None=None
 character_lock:str='Use uploaded character reference as identity source. Keep facial features, outfit, hairstyle and proportions identical.'
 duration:int=8

@app.post('/api/jobs')
def start_job(req:RunRequest):
 if req.dataset_id not in DATA:raise HTTPException(404,'Upload prompts first')
 data=validate(DATA[req.dataset_id]); ids=req.reel_ids or [r['id'] for r in data['reels']]
 selected=[r for r in data['reels'] if r['id'] in ids]
 if not selected:raise HTTPException(400,'No matching reels')
 if req.mode not in ('demo','veo'):raise HTTPException(400,'Unknown mode')
 if req.mode=='veo' and not (req.api_key or os.getenv('GEMINI_API_KEY')):raise HTTPException(400,'Provide a Gemini API key for Veo')
 jobid=uuid.uuid4().hex;folder=WORK/jobid;folder.mkdir()
 state={'id':jobid,'status':'queued','done':0,'total':sum(len(r['clips']) for r in selected),'message':'Queued','errors':[],'download':None}
 JOBS[jobid]=state
 # Keep credentials only in worker memory; never log, store in files or return them.
 thread=threading.Thread(target=process,args=(jobid,data,selected,req,folder),daemon=True);thread.start()
 return state

def process(jobid,data,reels,req,folder):
 state=JOBS[jobid];state['status']='running'; produced=[]
 try:
  for reel in reels:
   reel_folder=folder/f"reel_{reel['id']:03}";reel_folder.mkdir();clips=[]
   for clip in reel['clips']:
    state['message']=f"Reel {reel['id']} · Clip {clip['index']}"
    prompt='\n'.join(x for x in [data.get('universal_master',''),req.character_lock,reel.get('master',''),clip.get('motion',''), 'START FRAME: '+clip.get('start_frame',''), 'END FRAME: '+clip.get('end_frame',''), 'NARRATION REFERENCE: '+clip.get('voiceover',''), 'AVOID: '+data.get('universal_negative',''),reel.get('negative','')] if x)
    (reel_folder/f"clip_{clip['index']:02}_prompt.txt").write_text(prompt,encoding='utf8')
    output=reel_folder/f"clip_{clip['index']:02}.mp4"
    try:
     if req.mode=='demo':demo_clip(output,reel['title'],clip['index'])
     else:veo_clip(output,prompt,req.api_key or os.getenv('GEMINI_API_KEY'),req.duration)
     clips.append(output)
    except Exception as e:
     state['errors'].append(f"Reel {reel['id']} clip {clip['index']}: {str(e)[:350]}")
    state['done']+=1
   if clips:
    joined=reel_folder/f"reel_{reel['id']:03}.mp4"
    try:concat(clips,joined);produced.append(joined)
    except Exception as e:state['errors'].append(f"Reel {reel['id']} merge: {e}")
  (folder/'manifest.json').write_text(json.dumps({'mode':req.mode,'reels':[r['id'] for r in reels],'errors':state['errors']},indent=2))
  archive=folder/'output.zip'
  with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:
   for p in folder.rglob('*'):
    if p.is_file() and p!=archive:z.write(p,p.relative_to(folder))
  state['download']=f'/api/jobs/{jobid}/download';state['status']='completed' if not state['errors'] else 'partial';state['message']=f'{len(produced)} reels exported'
 except Exception as e:state['status']='failed';state['message']=str(e)[:400]

def demo_clip(output,title,index):
 # Real locally generated MP4 placeholder with progress, not AI video.
 if not shutil.which('ffmpeg'):raise RuntimeError('FFmpeg is required to create demo MP4 clips')
 colors=['0x14283d','0x20495b','0x365d54']; color=colors[(index-1)%3]
 cmd=['ffmpeg','-y','-f','lavfi','-i',f'color=c={color}:s=360x640:r=24','-t','2','-c:v','libx264','-pix_fmt','yuv420p','-movflags','+faststart',str(output)]
 subprocess.run(cmd,check=True,stdout=subprocess.DEVNULL,stderr=subprocess.PIPE,timeout=45)

def veo_clip(output,prompt,key,duration):
 # Official google-genai SDK. Availability, aspect ratio, model name and duration depend on account/model.
 from google import genai
 from google.genai import types
 client=genai.Client(api_key=key)
 op=client.models.generate_videos(model='veo-3.1-fast-generate-preview',prompt=prompt,config=types.GenerateVideosConfig(aspect_ratio='9:16',number_of_videos=1,duration_seconds=duration))
 for _ in range(120):
  if op.done:break
  time.sleep(10);op=client.operations.get(op)
 if not op.done:raise RuntimeError('Veo generation timed out; check billing and operation status')
 if op.error:raise RuntimeError(str(op.error))
 if not op.response or not op.response.generated_videos:raise RuntimeError('No video returned by Veo')
 video=op.response.generated_videos[0].video
 client.files.download(file=video)
 video.save(str(output))

def concat(clips,output):
 if not shutil.which('ffmpeg'):raise RuntimeError('FFmpeg is required to merge clips')
 listfile=output.parent/'concat.txt'
 listfile.write_text(''.join("file '"+str(p.resolve()).replace("'","'\\''")+"'\n" for p in clips))
 cmd=['ffmpeg','-y','-f','concat','-safe','0','-i',str(listfile),'-c:v','libx264','-pix_fmt','yuv420p','-an',str(output)]
 subprocess.run(cmd,check=True,stdout=subprocess.DEVNULL,stderr=subprocess.PIPE,timeout=180)

